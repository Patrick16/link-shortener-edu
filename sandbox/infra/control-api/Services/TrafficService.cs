using System.Text.Json;
using ControlApi.Models;
using ControlApi.Services.DataSources;
using ControlApi.Services.K6;

namespace ControlApi.Services;

// Orchestrates a traffic run: resolves the request's step sequence against EndpointRegistry,
// optionally preloads a data pool (DataPoolFetcher), builds the k6 command/env, then hands the
// actual container lifecycle off to K6ContainerRunner. The container-running and data-pool-preload
// mechanics used to live directly on this class - split out into Services/K6 and
// Services/DataSources respectively, pure move, no logic change (see .notes/PLAN.md's
// Simplification Backlog item 3).
public sealed class TrafficService : ITrafficService
{
    // The real routes a traffic run's step sequence can be built from - the server-side source of
    // truth (see EndpointDefinition) so k6-scripts/flow.js stays a generic interpreter with no
    // built-in knowledge of this app's actual routes, and Program.cs can validate a request before
    // ever starting a k6 container. email/password/originalLink are auto-generated by flow.js once
    // per iteration (not per step) specifically so a Register followed by a Login in the same
    // sequence shares one identity instead of two, which is what makes that pairing meaningful to
    // chain at all - see flow.js for where those get seeded.
    private static readonly IReadOnlyList<EndpointDefinition> EndpointRegistry =
    [
        new(
            "auth-api.register", "auth-api", "POST", "/register",
            """{"name":"flow-user","email":"{{email}}","password":"{{password}}"}""",
            new Dictionary<string, string>(), [],
            "Register a new user with this iteration's generated email/password"),
        new(
            "auth-api.login", "auth-api", "POST", "/login",
            """{"email":"{{email}}","password":"{{password}}"}""",
            new Dictionary<string, string> { ["token"] = "token" }, ["email", "password"],
            "Log in - only succeeds if a Register step ran earlier in the same sequence (they share one generated email/password per iteration); alone, every attempt is an expected 401"),
        new(
            "link-api.create", "link-api", "POST", "/Links",
            """{"originalLink":"{{originalLink}}"}""",
            new Dictionary<string, string> { ["hash"] = "shortenLink" }, [],
            "Create a short link"),
        new(
            "link-api.create-with-ttl", "link-api", "POST", "/Links",
            """{"originalLink":"{{originalLink}}","ttlSeconds":3600}""",
            new Dictionary<string, string> { ["hash"] = "shortenLink" }, [],
            "Create a short link with 1-hour TTL - exercises the TTL expiry feature"),
        new(
            "link-api.delete", "link-api", "DELETE", "/Links/{{hash}}",
            null,
            new Dictionary<string, string>(), ["hash", "token"],
            "Delete a short link - owner-only, needs a Register+Login earlier in the sequence (flow.js attaches {{token}} as a Bearer header automatically once a Login step has produced it - see flow.js's own comment)"),
        new(
            "link-api.list-deleted", "link-api", "GET", "/Links?deleted=true",
            null,
            new Dictionary<string, string>(), ["token"],
            "List deleted/expired links - the separate 'what's gone' view; needs a Register+Login earlier in the sequence, same as link-api.delete"),
        new(
            "redirect-api.resolve", "redirect-api", "GET", "/{{hash}}",
            null,
            new Dictionary<string, string>(), ["hash"],
            "Resolve a short link and redirect - uses the hash a Create step earlier in the sequence produced, a preloaded data pool if one was requested (see DataPoolFetcher.Registry), or a fixture link if neither ran. Right after Create in the same step, this often 404s: LinkApi returns the hash before ShortenerService has actually persisted it via RabbitMQ - a real eventual-consistency window, not a bug"),
        new(
            "reporting-api.stats", "reporting-api", "GET", "/reports/{{hash}}/summary",
            null,
            new Dictionary<string, string>(), ["hash", "token"],
            "Get click statistics for a short link (CQRS read model from ClickHouse) - owner-only, needs a Register+Login earlier in the sequence, same as link-api.delete"),
        new(
            "reporting-api.recent-clicks", "reporting-api", "GET", "/reports/{{hash}}/clicks",
            null,
            new Dictionary<string, string>(), ["hash", "token"],
            "List recent raw click documents for a short link (Mongo-backed, HedgedClickMetaQueryService) - the one HTTP route that actually reads clicks_meta_db, unlike reporting-api.stats (ClickHouse); owner-only, needs a Register+Login earlier in the sequence, same as link-api.delete"),
    ];

    // flow.js reads STEPS_JSON's fields as plain camelCase JS property names (step.serviceId,
    // step.pathTemplate, ...) - .NET's default serializer would emit PascalCase from the record's
    // own property names otherwise.
    private static readonly JsonSerializerOptions StepJsonOptions = new(JsonSerializerDefaults.Web);

    private sealed record ResolvedStep(
        string Id, string ServiceId, string Method, string PathTemplate, string? BodyTemplate,
        IReadOnlyDictionary<string, string> Produces, double PauseAfterSeconds);

    private readonly IInfraToggleService _infraToggle;
    private readonly string _k6ScriptsDir;
    private readonly K6ContainerRunner _containerRunner;
    private readonly DataPoolFetcher _dataPoolFetcher;

    public TrafficService(
        IConfiguration configuration, IInfraToggleService infraToggle, K6ContainerRunner containerRunner, DataPoolFetcher dataPoolFetcher)
    {
        _infraToggle = infraToggle;
        _containerRunner = containerRunner;
        _dataPoolFetcher = dataPoolFetcher;
        _k6ScriptsDir = configuration["K6:ScriptsDir"] ?? Path.Combine(AppContext.BaseDirectory, "k6-scripts");
    }

    public async Task<TrafficReport?> RunTrafficAsync(TrafficRequest request, Func<TrafficProgress, Task> onProgress, CancellationToken ct)
    {
        // Every run resolves its ordered step list against the server-side registry and executes
        // that exact sequence, once per k6 iteration, each step's own pause included - see flow.js.
        // Unknown ids are already rejected by Program.cs before this is ever called; the null
        // return here is just defense in depth.
        var resolvedSteps = new List<ResolvedStep>();
        foreach (var step in request.Steps)
        {
            var definition = EndpointRegistry.FirstOrDefault(e => e.Id == step.EndpointId);
            if (definition is null)
            {
                return null;
            }

            resolvedSteps.Add(new ResolvedStep(definition.Id, definition.ServiceId, definition.Method, definition.PathTemplate, definition.BodyTemplate, definition.Produces, step.PauseAfterSeconds));
        }

        if (resolvedSteps.Count == 0)
        {
            return null;
        }

        var scriptPath = Path.Combine(_k6ScriptsDir, "flow.js");
        if (!File.Exists(scriptPath))
        {
            return null;
        }

        // Checked/pulled here, before the data-pool preload below, so a missing image fails fast on
        // a cold environment instead of only surfacing after the preload has already spent time
        // hitting the real app (restores the pre-split ordering - see .notes/PLAN.md's
        // Simplification Backlog item 3 and the review report that caught this).
        await _containerRunner.EnsureImageReadyAsync(ct);

        // Read once for the whole run and threaded through as a parameter from here on (into
        // DataPoolFetcher.FetchAsync below, and into the k6 env vars further down) - not re-read
        // from _infraToggle at each use. The pool preload and the k6 run itself are minutes apart
        // for a long run; re-reading at each use let a toggle flip mid-run send the preload through
        // one URL and the actual run through the other, split across the same request (found during
        // review).
        var nginxBypassed = (await _infraToggle.GetInfraStatusAsync(ct)).NginxBypassed;

        // A requested data pool is fetched from the real app now, before k6 even starts, and
        // reported through the same onProgress callback as the run itself (Phase "preparing") so
        // the UI can show it instead of a frozen "starting..." while a few hundred requests happen
        // server-side. Null SourceId (unknown - already rejected by Program.cs) falls back to no
        // pool rather than failing the whole run over it.
        string? poolVar = null;
        IReadOnlyList<string>? pool = null;
        if (request.DataPool is { Count: > 0 } poolRequest)
        {
            var source = DataPoolFetcher.Registry.FirstOrDefault(s => s.Id == poolRequest.SourceId);
            if (source is not null)
            {
                pool = await _dataPoolFetcher.FetchAsync(source, poolRequest.Count, nginxBypassed, onProgress, ct);
                poolVar = source.ProducesVar;
            }
        }

        // Exactly one of three shapes drives how the run ends - k6's own executors, not reimplemented:
        // a target iteration count (shared-iterations - flat VUs, runs until that many iterations are
        // done, however long that takes), a custom ramp (--stage per segment of the UI's point graph -
        // ramping-vus), or a flat --vus/--duration constant. k6's periodic "running (...), X/Y VUs, N
        // complete" status line keeps the same overall shape in all three (confirmed against real runs
        // of each before relying on it) - only the elapsed-time formatting depends on total duration
        // (K6ProgressParser), and only iterations mode has no fixed total duration at all.
        var cmd = new List<string> { "run", "--no-color", "--summary-export", "/scripts/summary.json", "--vus", request.Vus.ToString() };
        int totalSeconds;
        int? targetIterations = request.Iterations;
        if (targetIterations is { } iterations)
        {
            cmd.Add("--iterations");
            cmd.Add(iterations.ToString());
            totalSeconds = 0;
        }
        else if (request.Stages is { Count: > 0 } stages)
        {
            foreach (var stage in stages)
            {
                cmd.Add("--stage");
                cmd.Add($"{stage.DurationSeconds}s:{stage.TargetVus}");
            }

            totalSeconds = stages.Sum(s => s.DurationSeconds);
        }
        else
        {
            cmd.Add("--duration");
            cmd.Add($"{request.DurationSeconds}s");
            totalSeconds = request.DurationSeconds;
        }

        cmd.Add("/scripts/scenario.js");

        // Nginx bypass only changes where k6 itself sends requests (LINK_API_URL/REDIRECT_API_URL
        // env vars flow.js already reads) - nginx keeps running either way, so
        // the frontend app's own manual use of it is unaffected. Bypassing means requests go
        // straight to the compose service name, which Docker's embedded DNS still round-robins
        // across replicas per-connection, but k6 keeps a connection alive per VU, so in practice
        // one VU sticks to whichever replica it first resolved - a fair demonstration of "no real
        // load balancing", not a trick. AuthApi was never behind nginx (see nginx.conf), so its URL
        // doesn't depend on the toggle at all. Reuses the nginxBypassed captured once at the top of
        // this method, not a fresh read - see that capture's own comment. ReportingApi IS behind
        // nginx now (backlog item 11 - nginx.conf's reporting_api_upstream), but k6's own traffic
        // generator still always goes straight to the compose service name regardless of the
        // toggle, same as AuthApi - there's no nginxBypassed ternary for either below, since
        // neither is on this toggle's own scope (link-api/redirect-api's hot-path round-robin
        // behavior).
        var env = new List<string>
        {
            $"LINK_API_URL=http://{(nginxBypassed ? "link-api:8080" : "nginx:8082")}",
            $"REDIRECT_API_URL=http://{(nginxBypassed ? "redirect-api:8080" : "nginx:8083")}",
            "AUTH_API_URL=http://auth-api:8080",
            "REPORTING_API_URL=http://reporting-api:8080",
            $"STEPS_JSON={JsonSerializer.Serialize(resolvedSteps, StepJsonOptions)}",
        };

        if (pool is { Count: > 0 })
        {
            env.Add($"POOL_VAR={poolVar}");
            env.Add($"POOL_MODE={request.DataPool!.Mode}");
            // Only used for flow.js's sequential round-robin spread - a best-effort approximation
            // even during a ramp (Vus there is just the ramp's starting point), which is fine since
            // sequential mode only promises even-ish coverage of the pool, not a strict guarantee.
            env.Add($"POOL_VUS_HINT={Math.Max(1, request.Vus)}");
            env.Add($"POOL_JSON={JsonSerializer.Serialize(pool, StepJsonOptions)}");
        }

        var stepIds = resolvedSteps.Select(s => s.Id).Distinct().ToList();

        return await _containerRunner.RunAsync(request, cmd, env, scriptPath, totalSeconds, targetIterations, stepIds, onProgress, ct);
    }

    public IReadOnlyList<EndpointDefinition> ListKnownEndpoints() => EndpointRegistry;

    public IReadOnlyList<DataSourceDefinition> ListDataSources() => DataPoolFetcher.Registry;
}
